import type { Journey } from '../../../.claude/skills/verify-mylder/scripts/drive.ts'
import { esc, top, pillOf, spot, mapParam, waitLanded, headerBottom, box } from './lib.ts'

/** Follow, if on, ends at a press on the pill: following a moving bus, a press flies to the latest trip, whose
 * panel shows Follow off, and the camera then stays put; following the latest trip itself, a press turns it off. */
export default async ({ page, step, expect }: Journey) => {
  await page.setViewportSize({ width: 1280, height: 800 })
  const s0 = await (await page.request.get('/api/snapshot')).json()
  const t = (await top(page))!
  const bus = s0.trips.filter((x: any) => x.mode === 'bus' && x.state === 'estimated' && !x.waiting && !x.cancelled && x.key !== t.key).sort((a: any, b: any) => a.key < b.key ? -1 : 1)[0]
  console.log('top', JSON.stringify(t), 'bus to follow', bus.key, bus.line, bus.headsign)
  await page.goto(`/en?trip=${encodeURIComponent(bus.key)}`)
  const pill = pillOf(page)
  await expect(pill).toBeVisible({ timeout: 60000 })
  const busPanel = page.getByRole('dialog', { name: new RegExp(`to ${esc(bus.headsign)}`) })
  await expect(busPanel).toBeVisible()
  await busPanel.getByRole('button', { name: 'Follow' }).click()
  await expect(busPanel.getByRole('button', { name: 'Follow' })).toHaveAttribute('aria-pressed', 'true')
  await page.waitForTimeout(3000)
  await step('following a bus')
  const m1 = mapParam(page)
  await page.waitForTimeout(8000)
  const m2 = mapParam(page)
  console.log('following the bus: map', m1, '->', m2)
  await step('following a bus 8 s later')
  const sh1 = await page.screenshot({ clip: { x: 400, y: 200, width: 480, height: 400 } })
  await page.waitForTimeout(4000)
  const sh2 = await page.screenshot({ clip: { x: 400, y: 200, width: 480, height: 400 } })
  console.log('map picture moving under Follow:', !sh1.equals(sh2))
  await pill.click()
  await step('pill pressed while following the bus')
  const trip = page.getByRole('dialog', { name: new RegExp(`to ${esc(t.headsign)}`) })
  await expect(trip).toBeVisible()
  await expect(page).toHaveURL(new RegExp(`trip=${esc(encodeURIComponent(t.key))}`))
  await waitLanded(page)
  await expect(trip.getByRole('button', { name: 'Follow' })).toHaveAttribute('aria-pressed', 'false')
  const m3 = mapParam(page); const s3 = await spot(page)
  await page.waitForTimeout(10000)
  const m4 = mapParam(page); const s4 = await spot(page)
  console.log('after the press: map', m3, '->', m4, '; ring', s3.key, s3.at, '->', s4.at)
  await step('10 s after the press')
  expect(m4, 'the camera stays put: no Follow left on').toBe(m3)
  expect(s4.key).toBe(t.key)
  const [x, y] = s4.at!.split(' ').map(Number)
  const hb = await headerBottom(page)
  const ob = await box(page, page.getByRole('dialog', { name: 'Overview' }))
  const pb = await box(page, trip)
  console.log('ring', x, y, 'header', hb, 'sheet right', ob.right, 'panel left', pb.left)
  expect(y - 12).toBeGreaterThan(hb)
  expect(x - 12).toBeGreaterThan(ob.right)
  expect(x + 12).toBeLessThan(pb.left)
  // Following the latest trip itself, then pressing the pill
  await trip.getByRole('button', { name: 'Follow' }).click()
  await expect(trip.getByRole('button', { name: 'Follow' })).toHaveAttribute('aria-pressed', 'true')
  await step('following the latest trip')
  await pill.click()
  await expect(trip.getByRole('button', { name: 'Follow' })).toHaveAttribute('aria-pressed', 'false')
  await waitLanded(page)
  await step('pill pressed while following it: Follow off')
}
