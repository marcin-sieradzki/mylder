import type { Journey } from '../../../.claude/skills/verify-mylder/scripts/drive.ts'
// vehicle-detail: from the list, facts, Follow, Show whole line, close, missing; SIRI-ET Estimated bus
export default async ({ page, step, expect }: Journey) => {
  await page.goto('/en')
  await expect(page.getByRole('banner').getByText(/^Updated /)).toBeVisible({ timeout: 60000 })
  await page.getByRole('dialog', { name: 'Overview' }).getByRole('tab', { name: /^Vehicles/ }).click()
  const row = page.getByRole('table', { name: 'Vehicles' }).getByRole('link').first()
  const dest = (await row.innerText()).trim()
  await step('vehicles list')
  await row.click()
  await expect(page).toHaveURL(/[?&]trip=/)
  const d = page.getByRole('dialog').filter({ has: page.getByRole('button', { name: 'Follow' }) })
  await expect(d).toBeVisible()
  console.log('row', dest, 'dialog', await d.getAttribute('aria-label'))
  for (const w of ['Delay', 'Last seen', 'Next stop']) await expect(d.getByText(w, { exact: true }).first()).toBeVisible()
  await expect(d.getByRole('list', { name: 'Stops' })).toBeVisible()
  await step('trip open from the list')
  await d.getByRole('button', { name: 'Follow' }).click()
  await expect(d.getByRole('button', { name: 'Follow' })).toHaveAttribute('aria-pressed', 'true')
  await step('follow on')
  await d.getByRole('button', { name: 'Show whole line' }).click()
  const chip = page.getByRole('button', { name: /^Showing: line .* · Clear$/ })
  await expect(chip).toBeVisible()
  await page.waitForTimeout(2500)
  await step('whole line')
  await chip.click()
  await expect(chip).toBeHidden()
  await page.keyboard.press('Escape')
  await expect(d).toBeHidden()
  await expect(page).not.toHaveURL(/[?&]trip=/)
  await step('closed')
  await page.goto('/en?trip=nothing')
  await expect(page.getByRole('dialog', { name: 'Trip not found' })).toBeVisible()
  await step('missing')
  const s = await (await page.request.get('/api/snapshot')).json()
  const bus = s.trips.find((x: any) => x.mode === 'bus' && x.state === 'estimated' && x.delay >= 120 && !x.cancelled)
  await page.goto(`/en?trip=${encodeURIComponent(bus.key)}`)
  const bd = page.getByRole('dialog', { name: new RegExp(`to ${bus.headsign.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}`) })
  await expect(bd).toContainText('Estimated')
  await expect(bd).toContainText(/Estimated from the timetable and a delay of \+\d+ min/)
  await expect(bd).toContainText(/Timetable\s+and\s+Rejseplanen.s\s+delays\s*·\s*updated\s+\d\d:\d\d:\d\d/)
  await step('siri-et bus')
}
